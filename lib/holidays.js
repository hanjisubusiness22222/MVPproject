/**
 * 지정된 연(year)과 월(month)의 대한민국 공휴일 목록 반환
 * @param {number} year 
 * @param {number} month (1~12)
 * @returns {Array<{ date: string, name: string }>}
 */
export function getKoreanHolidays(year, month) {
  const y = Number(year);
  const m = Number(month);
  if (!Number.isInteger(y) || !Number.isInteger(m) || m < 1 || m > 12) {
    return [];
  }

  const mm = String(m).padStart(2, '0');
  const results = [];

  // 1. 고정 양력 공휴일 체크
  for (const [md, name] of Object.entries(SOLAR_HOLIDAYS)) {
    if (md.startsWith(mm + '-')) {
      results.push({
        date: `${y}-${md}`,
        name
      });
    }
  }

  // 2. 가변/음력 공휴일 체크
  const yearVar = LUNAR_AND_VARIABLE_HOLIDAYS[y];
  if (yearVar) {
    for (const [md, name] of Object.entries(yearVar)) {
      if (md.startsWith(mm + '-')) {
        // 이미 동일 날짜가 있는지 체크 후 병합/추가
        const existing = results.find((r) => r.date === `${y}-${md}`);
        if (existing) {
          if (!existing.name.includes(name)) {
            existing.name += ` · ${name}`;
          }
        } else {
          results.push({
            date: `${y}-${md}`,
            name
          });
        }
      }
    }
  }

  // 날짜순 정렬
  results.sort((a, b) => a.date.localeCompare(b.date));
  return results;
}
